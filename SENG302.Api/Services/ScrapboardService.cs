using Microsoft.EntityFrameworkCore;
using SENG302.Api.DataAccess;
using SENG302.Api.Helpers.Validators;
using SENG302.Api.Models.Entities;

namespace SENG302.Api.Services;

public interface IScrapboardService
{
    public Task<Scrapboard?> GetScrapboardByTripAsync(int tripId);
    public Task<Scrapboard> CreateScrapboardAsync(int tripId);
    public Task SaveScrapboardAsync(int id, string elements, List<IFormFile> files, IFormFile thumbnail);
    public Task<CustomFile> GetScrapboardThumbnailAsync(int tripId);
    public Task DeleteScrapboardAsync(int tripId);
}

public class ScrapboardService : IScrapboardService
{
    private readonly ITripService _tripService;
    private readonly IDbContextFactory<DatabaseContext> _dbContextFactory;
    private readonly IFileService _fileService;

    public ScrapboardService(ITripService tripService, IDbContextFactory<DatabaseContext> dbContextFactory, IFileService fileService)
    {
        _dbContextFactory = dbContextFactory;
        _tripService = tripService;
        _fileService = fileService;
    }

    /// <summary>
    /// given a trip and user id, creates a scrapboard, and changes the trip's scrapboard id
    /// to be the id of the newly created one.
    /// If the trip's scrapboardid is greater than -1, then throw argument error as that trip
    /// must have a scrapboard attached to it.
    /// </summary>
    /// <param name="tripId"></param>
    /// <returns>the newly created scrapboard</returns>
    /// <exception cref="ArgumentException"></exception>
    public async Task<Scrapboard> CreateScrapboardAsync(int tripId)
    {
        await using var context = await _dbContextFactory.CreateDbContextAsync();
        var trip = await _tripService.GetTripByIdAsync(tripId);
        //greater than -1 means the trip has a scrapboard already
        if (trip.HasScrapboard)
        {
            throw new ArgumentException("This trip already has a Scrapboard.");
        }
        var newScrapboard = new Scrapboard()
        {
            TripId = tripId
        };
        await _tripService.UpdateScrapboardReferenceAsync(tripId);
        context.Set<Scrapboard>().Add(newScrapboard);
        await context.SaveChangesAsync();

        return newScrapboard;
    }

    /// <summary>
    /// scrapboards use their tripid as their primary key, so
    /// given a trip's id, return it's corresponding scrapboard
    /// </summary>
    /// <param name="tripId"></param>
    /// <returns>the scrapboard db item</returns>
    /// <exception cref="ArgumentException"></exception>
    public async Task<Scrapboard?> GetScrapboardByTripAsync(int tripId)
    {
        await using var context = await _dbContextFactory.CreateDbContextAsync();

        var scrapboard = await context.Scrapboards.FirstOrDefaultAsync(t => t.TripId == tripId);
        return scrapboard;
    }

    /// <summary>
    /// Saves the scrapboard elements to the scrapboard entity, and creates files for image uploads and scrapboard
    /// thumbnail. Also deletes old files and thumbnail if available
    /// </summary>
    /// <param name="id">The scrapboard id</param>
    /// <param name="elements">string representation of elements json array from excalidraw</param>
    /// <param name="files">list of IFormFile objects that are the files used by Excalidraw</param>
    /// <param name="thumbnail">thumbnail image generated by Excalidraw</param>
    public async Task SaveScrapboardAsync(int id, string elements, List<IFormFile> files, IFormFile thumbnail)
    {
        await using var context = await _dbContextFactory.CreateDbContextAsync();
        Trip trip = await _tripService.GetTripByIdAsync(id);
        var ownerId = trip.UserId;
        
        var fileIdList = new List<int>();
        foreach (var file in files)
        {
            CustomFile customFile = await _fileService.SaveFileAsync(file, ownerId);
            fileIdList.Add(customFile.Id);
        }
        
        CustomFile thumbnailFile = await _fileService.SaveFileAsync(thumbnail, ownerId);

        if (!ImageValidator.IsValidFilesize(thumbnail))
        {
            throw new FileSizeExceededException("Scrapboard too large, reduce the size of your scrapboard.");
        }
        
        if (!ImageValidator.IsValidMimeType(thumbnail))
        {
            throw new FileMimeTypeInvalidException("Invalid Mime Type");
        }        
        
        var scrapboard = await context.Scrapboards.FirstOrDefaultAsync(s => s.TripId == id);

        if (scrapboard == null)
        {
            throw new KeyNotFoundException("Scrapboard not found.");
        }
        
        // collects old scrapboard files and thumbnail id's to be deleted
        List<int> oldScrapboardFiles = scrapboard.Files;
        if (scrapboard.Thumbnail != -1)
        {
            oldScrapboardFiles.Add(scrapboard.Thumbnail);
        }
        
        scrapboard.Elements = elements;
        scrapboard.Files = fileIdList;
        scrapboard.Thumbnail = thumbnailFile.Id;

        // deletes old images related to scrapboard.
        foreach (var fileId in oldScrapboardFiles)
        {
            CustomFile file = await _fileService.GetFileByIdAsync(fileId);
            await _fileService.DeleteFileAsync(file.FileKey);
        }
        
        context.Scrapboards.Update(scrapboard);
        await context.SaveChangesAsync();
    }

    /// <summary>
    /// Gets the thumbnail of a scrapboard
    /// </summary>
    /// <param name="tripId">ID of the trip associated with the scrapboard</param>
    /// <returns>Bytestream of the thumbnail</returns>
    /// <exception cref="KeyNotFoundException">Scrapboard not found</exception>
    public async Task<CustomFile> GetScrapboardThumbnailAsync(int tripId)
    {
        await using var context = await _dbContextFactory.CreateDbContextAsync();

        Scrapboard? scrapboard = await GetScrapboardByTripAsync(tripId);
        if (scrapboard == null)
        {
            throw new KeyNotFoundException("Scrapboard not found.");
        }
        if (scrapboard.Thumbnail == -1)
        {
            throw new FileNotFoundException("Scrapboard has no thumbnail");
        }

        var thumbnailFile = await _fileService.GetFileByIdAsync(scrapboard.Thumbnail);
        return thumbnailFile;
    }
    
    /// <summary>
    /// Deletes a scrapboard and its files
    /// </summary>
    /// <param name="tripId">The trip id of the scrapboard to be deleted.</param>
    /// <exception cref="KeyNotFoundException">Scrapboard not found.</exception>
    public async Task DeleteScrapboardAsync(int tripId)
    {
        await using var context = await _dbContextFactory.CreateDbContextAsync();
        Scrapboard? scrapboard = await context.Scrapboards.FirstOrDefaultAsync(t => t.TripId == tripId);
        if (scrapboard == null)
        {
            throw new KeyNotFoundException("Scrapboard not found.");
        }
        
        List<int> oldScrapboardFiles = scrapboard.Files;
        if (scrapboard.Thumbnail != -1)
        {
            oldScrapboardFiles.Add(scrapboard.Thumbnail);
        }
        
        foreach (var fileId in oldScrapboardFiles)
        {
            CustomFile file = await _fileService.GetFileByIdAsync(fileId);
            await _fileService.DeleteFileAsync(file.FileKey);
        }
        
        await context.Scrapboards.Where(s => s.TripId == tripId).ExecuteDeleteAsync();
    }
}